begin;

create table if not exists public.brain_feedback (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  agent text not null check (agent in (
    'resume_analyst',
    'role_researcher',
    'fit_analyst',
    'application_strategist',
    'truth_guard'
  )),
  helpful boolean not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (owner_id, agent)
);

revoke all on public.brain_feedback from public, anon;
alter table public.brain_feedback enable row level security;
alter table public.brain_feedback force row level security;
drop policy if exists owner_isolation on public.brain_feedback;
create policy owner_isolation on public.brain_feedback
  for all to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));
grant select, insert, update, delete on public.brain_feedback to authenticated;
grant usage, select on sequence public.brain_feedback_id_seq to authenticated;

create or replace function public.applypilot_master_brain_ready()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select exists (
    select 1
    from pg_catalog.pg_class c
    join pg_catalog.pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
      and c.relname = 'brain_feedback'
      and c.relrowsecurity
      and c.relforcerowsecurity
  ) and exists (
    select 1
    from pg_catalog.pg_policies p
    where p.schemaname = 'public'
      and p.tablename = 'brain_feedback'
      and p.policyname = 'owner_isolation'
      and p.cmd = 'ALL'
      and p.roles @> array['authenticated']::name[]
      and position('owner_id' in coalesce(p.qual, '')) > 0
      and position('auth.uid' in coalesce(p.qual, '')) > 0
      and position('owner_id' in coalesce(p.with_check, '')) > 0
      and position('auth.uid' in coalesce(p.with_check, '')) > 0
  );
$$;

revoke all on function public.applypilot_master_brain_ready() from public, anon;
grant execute on function public.applypilot_master_brain_ready() to authenticated;

commit;
