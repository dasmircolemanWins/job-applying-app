do $$
declare
  table_name text;
  identity_sequence text;
begin
  foreach table_name in array array[
    'settings', 'profile', 'rules', 'stories', 'resumes', 'experience_bank',
    'jobs', 'application_kits', 'applications', 'blocked_items', 'parked_items',
    'agent_runs', 'daily_reports', 'assist_sessions'
  ] loop
    execute format('revoke all on public.%I from public, anon', table_name);
    execute format('alter table public.%I enable row level security', table_name);
    execute format('alter table public.%I force row level security', table_name);
    execute format('drop policy if exists owner_isolation on public.%I', table_name);
    execute format(
      'create policy owner_isolation on public.%I for all to authenticated using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()))',
      table_name
    );
    execute format('grant select, insert, update, delete on public.%I to authenticated', table_name);
    identity_sequence := pg_get_serial_sequence(format('public.%I', table_name), 'id');
    if identity_sequence is not null then
      execute format('revoke all on sequence %s from public, anon', identity_sequence);
      execute format('grant usage, select on sequence %s to authenticated', identity_sequence);
    end if;
  end loop;
end $$;

