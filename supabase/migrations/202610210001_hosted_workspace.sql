drop policy if exists applypilot_user_files_select on storage.objects;
drop policy if exists applypilot_user_files_insert on storage.objects;
drop policy if exists applypilot_user_files_update on storage.objects;
drop policy if exists applypilot_user_files_delete on storage.objects;

create policy applypilot_user_files_select on storage.objects
  for select to authenticated
  using (bucket_id = 'user-files' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy applypilot_user_files_insert on storage.objects
  for insert to authenticated
  with check (bucket_id = 'user-files' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy applypilot_user_files_update on storage.objects
  for update to authenticated
  using (bucket_id = 'user-files' and (storage.foldername(name))[1] = (select auth.uid())::text)
  with check (bucket_id = 'user-files' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy applypilot_user_files_delete on storage.objects
  for delete to authenticated
  using (bucket_id = 'user-files' and (storage.foldername(name))[1] = (select auth.uid())::text);

create or replace function public.applypilot_workspace_ready()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public, storage
as $$
  select
    (
      select count(*) = 14
      from pg_catalog.pg_class c
      join pg_catalog.pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public'
        and c.relname = any (array[
          'settings', 'profile', 'rules', 'stories', 'resumes', 'experience_bank',
          'jobs', 'application_kits', 'applications', 'blocked_items', 'parked_items',
          'agent_runs', 'daily_reports', 'assist_sessions'
        ]::name[])
        and c.relrowsecurity
        and c.relforcerowsecurity
    )
    and (
      select count(*) = 14
      from pg_catalog.pg_policies p
      where p.schemaname = 'public'
        and p.tablename = any (array[
          'settings', 'profile', 'rules', 'stories', 'resumes', 'experience_bank',
          'jobs', 'application_kits', 'applications', 'blocked_items', 'parked_items',
          'agent_runs', 'daily_reports', 'assist_sessions'
        ]::name[])
        and p.policyname = 'owner_isolation'
        and p.cmd = 'ALL'
        and p.roles @> array['authenticated']::name[]
        and position('owner_id' in coalesce(p.qual, '')) > 0
        and position('auth.uid' in coalesce(p.qual, '')) > 0
        and position('owner_id' in coalesce(p.with_check, '')) > 0
        and position('auth.uid' in coalesce(p.with_check, '')) > 0
    )
    and (
      select count(*) = 14
      from pg_catalog.pg_policies p
      where p.schemaname = 'public'
        and p.tablename = any (array[
          'settings', 'profile', 'rules', 'stories', 'resumes', 'experience_bank',
          'jobs', 'application_kits', 'applications', 'blocked_items', 'parked_items',
          'agent_runs', 'daily_reports', 'assist_sessions'
        ]::name[])
    )
    and (
      select count(*) = 4
      from pg_catalog.pg_policies p
      where p.schemaname = 'storage'
        and p.tablename = 'objects'
    )
    and (
      select count(*) = 4
      from pg_catalog.pg_policies p
      where p.schemaname = 'storage'
        and p.tablename = 'objects'
        and p.policyname = any (array[
          'applypilot_user_files_select', 'applypilot_user_files_insert',
          'applypilot_user_files_update', 'applypilot_user_files_delete'
        ]::name[])
        and p.roles @> array['authenticated']::name[]
        and (
          position('user-files' in coalesce(p.qual, '')) > 0
          or position('user-files' in coalesce(p.with_check, '')) > 0
        )
        and (
          position('auth.uid' in coalesce(p.qual, '')) > 0
          or position('auth.uid' in coalesce(p.with_check, '')) > 0
        )
        and (
          position('foldername' in coalesce(p.qual, '')) > 0
          or position('foldername' in coalesce(p.with_check, '')) > 0
        )
    )
    and (
      select c.relrowsecurity
      from pg_catalog.pg_class c
      where c.oid = 'storage.objects'::regclass
    )
    and exists (
      select 1 from storage.buckets b
      where b.id = 'user-files' and not b.public
    );
$$;
revoke all on function public.applypilot_workspace_ready() from public, anon;
grant execute on function public.applypilot_workspace_ready() to authenticated;

commit;
